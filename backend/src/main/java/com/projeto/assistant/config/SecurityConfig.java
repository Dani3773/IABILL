package com.projeto.assistant.config;

import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.web.SecurityFilterChain;

// ATENÇÃO: esta configuração é TEMPORÁRIA, apenas para desenvolvimento local.
// Ela libera todos os endpoints sem autenticação.
// Será substituída por autenticação JWT + isolamento por tenant nos próximos passos.
@Configuration
public class SecurityConfig {

    @Bean
    public SecurityFilterChain filterChain(HttpSecurity http) throws Exception {
        http
                .csrf(csrf -> csrf.disable())
                .authorizeHttpRequests(auth -> auth.anyRequest().permitAll());

        return http.build();
    }
}